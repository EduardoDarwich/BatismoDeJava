package NivelIntermediario.construtores;

public class Hokages {

    public String nome;
    public int idade;
    public boolean vivo;
    public int missoes;
    public int altura;

    public Hokages() {
    }

    public Hokages(String nome, int idade, boolean vivo, int missoes, int altura) {
        this.nome = nome;
        this.idade = idade;
        this.vivo = vivo;
        this.missoes = missoes;
        this.altura = altura;
    }
}
